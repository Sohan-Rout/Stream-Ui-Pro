const PAGE = 120;
const SIZES = [16, 20, 24, 32] as const;
const STROKES = [1.5, 1.75, 2, 2.5] as const;
const ANIMATIONS = ["none", ...iconAnimations] as const;
const TRIGGERS = ["hover", "loop"] as const satisfies readonly IconTrigger[];
const COPY_AS = ["jsx", "svg"] as const;

type IconSet = "icons" | "brands" | "emojis";
/** Brand logos (Simple Icons via react-icons/si), generated by scripts/build-brand-icons.ts. */
type BrandIcon = { name: string; slug: string };

/** The open catalog lives in the URL (?catalog=brands) so it can be linked. */
const CATALOG_EVENT = "streamui:icon-catalog";
function subscribeCatalog(onChange: () => void) {
  window.addEventListener("popstate", onChange);
  window.addEventListener(CATALOG_EVENT, onChange);
  return () => {
    window.removeEventListener("popstate", onChange);
    window.removeEventListener(CATALOG_EVENT, onChange);
  };
}
const readCatalog = (): IconSet => {
  const c = new URLSearchParams(window.location.search).get("catalog");
  return c === "brands" || c === "emojis" ? c : "icons";
};
function openCatalog(set: IconSet) {
  const url = new URL(window.location.href);
  if (set !== "icons") url.searchParams.set("catalog", set);
  else url.searchParams.delete("catalog");
  window.history.replaceState(window.history.state, "", url);
  window.dispatchEvent(new Event(CATALOG_EVENT));
}

const SAMPLE_ICONS = [Rocket, Heart, Zap, Sparkles];
const SAMPLE_BRANDS = ["github", "figma", "react", "spotify"];

/** One of the two catalog cards: a strip of samples, the name, the count, and whether it's open. */
function CatalogCard({
  open,
  title,
  description,
  count,
  tone,
  onOpen,
  children,
}: {
  open: boolean;
  title: string;
  description: string;
  count: string;
  tone: string;
  onOpen: () => void;
  children: ReactNode;
}) {
  return (
    <button
      type="button"
      aria-pressed={open}
      onClick={onOpen}
      className={cn(
        "group flex cursor-pointer flex-col gap-5 border-2 border-ink p-5 text-left transition-[translate,box-shadow,background-color] duration-150 focus-visible:outline-3 focus-visible:outline-offset-4 focus-visible:outline-ink motion-reduce:transition-none sm:p-6",
        open ? `${tone} -translate-x-0.5 -translate-y-0.5 text-on-bright shadow-brutal-lg` : "bg-paper-raised shadow-brutal hover:-translate-x-0.5 hover:-translate-y-0.5 hover:shadow-brutal-lg",
      )}
    >
      <span aria-hidden className="flex gap-2">
        {children}
      </span>
      <span className="flex flex-col gap-1.5">
        <span className="flex flex-wrap items-center gap-3">
          <span className="font-display text-2xl tracking-tight">{title}</span>
          <span className="border-2 border-ink bg-paper-raised px-1.5 font-mono text-xs font-bold text-ink">{count}</span>
        </span>
        <span className={cn("text-sm leading-relaxed", open ? "" : "text-ink-muted")}>{description}</span>
      </span>
      <span
        className={cn(
          "mt-auto inline-flex items-center gap-1.5 self-start border-2 border-ink px-2.5 py-1 font-mono text-xs font-bold uppercase shadow-brutal-sm",
          open ? "bg-ink text-paper" : "bg-lime text-on-bright",
        )}
      >
        {open ? (
          <>
            <Check aria-hidden className="size-3.5" strokeWidth={3} /> Browsing
          </>
        ) : (
          <>
            Open <ArrowRight aria-hidden className="size-3.5 transition-transform duration-150 group-hover:translate-x-0.5 motion-reduce:transition-none" />
          </>
        )}
      </span>
    </button>
  );
}

/** The emoji catalog: each emoji in its still and animated variants, copyable as standalone SVGs. */
function EmojiCatalog({ copied, onCopied }: { copied: string | null; onCopied: (s: string) => void }) {
  const [palette, setPalette] = useState<"mono" | "color">("mono");
  const [query, setQuery] = useState("");
  const colored = palette === "color";
  const q = query.trim().toLowerCase();
  const shown = q ? emojis.filter((e) => e.name.toLowerCase().includes(q) || e.slug.includes(q) || e.char === q) : emojis;
  async function copy(button: HTMLElement, label: string) {
    const svg = button.closest("li")?.querySelector(`[data-variant="${label}"] svg`);
    if (!svg) return;
    try {
      await navigator.clipboard.writeText(svg.outerHTML);
      onCopied(label);
    } catch {
      // Clipboard blocked; nothing useful to do.
    }
  }
  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-wrap items-center gap-4">
      <label htmlFor="emoji-search" className="sr-only">
        Search emojis
      </label>
      <Input
        id="emoji-search"
        type="search"
        icon={<Search />}
        value={query}
        onChange={(e) => setQuery(e.target.value)}
        placeholder={`Search ${emojis.length} faces… try "cry" or 😂`}
        className="max-w-sm flex-1"
      />
      <div role="group" aria-label="Emoji colors" className="flex self-start border-2 border-ink shadow-brutal-sm">
        {(
          [
            ["mono", "Black & white"],
            ["color", "Colored"],
          ] as const
        ).map(([id, label]) => (
          <button
            key={id}
            type="button"
            aria-pressed={palette === id}
            onClick={() => setPalette(id)}
            className={cn(
              "cursor-pointer px-4 py-2 font-mono text-xs font-bold uppercase transition-colors duration-150 not-first:border-l-2 not-first:border-ink",
              palette === id ? "bg-ink text-paper" : "bg-paper-raised hover:bg-lime-soft",
            )}
          >
            {label}
          </button>
        ))}
      </div>
      </div>
      <p aria-live="polite" className="font-mono text-xs text-ink-muted">
        {copied ? <span className="bg-lime px-1.5 py-0.5 font-bold text-on-bright">copied {copied} SVG</span> : "Click a variant to copy it as an SVG. Animated ones carry their own CSS and hold still for reduced motion."}
      </p>
      {shown.length === 0 && <p className="font-bold">No faces match “{query}”.</p>}
      <ul className="grid grid-cols-1 gap-5 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
        {shown.map((e) => (
          <li key={e.slug} className="flex flex-col border-2 border-ink bg-paper-raised shadow-brutal">
            <div className="grid grid-cols-2 border-b-2 border-ink">
              {(["still", "animated"] as const).map((v) => (
                <button
                  key={v}
                  type="button"
                  data-variant={`${e.slug} ${colored ? "colored " : ""}${v}`}
                  aria-label={`Copy ${e.name} (${colored ? "colored, " : ""}${v}) as SVG`}
                  onClick={(ev) => copy(ev.currentTarget, `${e.slug} ${colored ? "colored " : ""}${v}`)}
                  className="group flex cursor-pointer flex-col items-center gap-2 bg-paper bg-dots px-2 pt-4 pb-2 transition-colors duration-150 not-first:border-l-2 not-first:border-ink hover:bg-lime-soft focus-visible:relative focus-visible:outline-3 focus-visible:-outline-offset-4 focus-visible:outline-blue"
                >
                  <e.Component animated={v === "animated"} colored={colored} size={72} />
                  <span className="border-2 border-ink bg-paper-raised px-1.5 font-mono text-xs font-bold uppercase group-hover:bg-lime">{v}</span>
                </button>
              ))}
            </div>
            <div className="flex items-center justify-between gap-2 px-3 py-2.5">
              <span className="truncate font-display text-sm tracking-tight">{e.name}</span>
              <span aria-hidden className="text-base">{e.char}</span>
            </div>
          </li>
        ))}
      </ul>
    </div>
  );
}

/** A small tile for a sample glyph on a catalog card. */
const SampleTile = ({ children }: { children: ReactNode }) => (
  <span className="grid size-9 shrink-0 place-items-center border-2 border-ink bg-paper-raised text-ink">{children}</span>
);


/** "arrow-up-right" → "ArrowUpRight", the name you import from lucide-react. */
export function toComponentName(name: string) {
  return name.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
}

function Segmented<T extends string | number>({
  label,
  options,
  value,
  onChange,
}: {
  label: string;
  options: readonly T[];
  value: T;
  onChange: (v: T) => void;
}) {
  return (
    <div className="flex flex-wrap items-center gap-3">
      <span className="font-mono text-xs text-ink-muted uppercase">{label}</span>
      <div role="group" aria-label={label} className="flex flex-wrap border-2 border-ink">
        {options.map((o) => (
          <button
            key={o}
            type="button"
            aria-pressed={value === o}
            onClick={() => onChange(o)}
            className={cn(
              "min-w-11 cursor-pointer px-2 py-1.5 font-mono text-xs font-bold transition-colors duration-150 not-first:border-l-2 not-first:border-ink",
              value === o ? "bg-lime text-on-bright" : "bg-paper-raised hover:bg-lime-soft",
            )}
          >
            {o}
          </button>
        ))}
      </div>
    </div>
  );
}

export function IconBrowser() {
  const set = useSyncExternalStore(subscribeCatalog, readCatalog, () => "icons" as IconSet);
  const [brands, setBrands] = useState<BrandIcon[] | null>(null);
  const [brandError, setBrandError] = useState(false);
  const [copyAs, setCopyAs] = useState<(typeof COPY_AS)[number]>("jsx");
  const [query, setQuery] = useState("");
  const deferredQuery = useDeferredValue(query);
  const [size, setSize] = useState<(typeof SIZES)[number]>(24);
  const [stroke, setStroke] = useState<(typeof STROKES)[number]>(1.75);
  const [animation, setAnimation] = useState<IconAnimation | "none">("none");
  const [trigger, setTrigger] = useState<(typeof TRIGGERS)[number]>("hover");
  const [limit, setLimit] = useState(PAGE);
  const [copied, setCopied] = useState<string | null>(null);

  // Brand logos load only when their tab is first opened.
  useEffect(() => {
    if (set !== "brands" || brands) return;
    let live = true;
    fetch(`${BRAND_DIR}/index.json`)
      .then((r) => (r.ok ? r.json() : Promise.reject(r.status)))
      .then((list: BrandIcon[]) => live && setBrands(list))
      .catch(() => live && setBrandError(true));
    return () => {
      live = false;
    };
  }, [set, brands]);

  const matches = useMemo(() => {
    const q = deferredQuery.trim().toLowerCase().replace(/\s+/g, "-");
    return q ? iconNames.filter((n) => n.includes(q)) : iconNames;
  }, [deferredQuery]);

  const brandMatches = useMemo(() => {
    const q = deferredQuery.trim().toLowerCase().replace(/[\s.-]+/g, "");
    const list = brands ?? [];
    return q ? list.filter((b) => b.slug.includes(q)) : list;
  }, [deferredQuery, brands]);

  useEffect(() => {
    if (!copied) return;
    const t = setTimeout(() => setCopied(null), 1600);
    return () => clearTimeout(t);
  }, [copied]);

  async function copy(name: IconName) {
    const icon = `<${toComponentName(name)} />`;
    const triggerProp = trigger === "hover" ? "" : ` trigger="${trigger}"`;
    const jsx =
      animation === "none"
        ? icon
        : `<AnimatedIcon animation="${animation}"${triggerProp}>${icon}</AnimatedIcon>`;
    try {
      await navigator.clipboard.writeText(jsx);
      setCopied(jsx);
    } catch {
      // Clipboard blocked; nothing useful to do.
    }
  }

  async function copyBrand(b: BrandIcon) {
    try {
      const text = copyAs === "svg" ? await fetch(`${BRAND_DIR}/${b.slug}.svg`).then((r) => r.text()) : `<${b.name} />`;
      await navigator.clipboard.writeText(text);
      setCopied(copyAs === "svg" ? `${b.slug}.svg` : `<${b.name} />`);
    } catch {
      // Clipboard or network blocked; nothing useful to do.
    }
  }

  const brandsMode = set === "brands";
  const count = brandsMode ? brandMatches.length : matches.length;
  const total = brandsMode ? (brands?.length ?? 0) : iconNames.length;
  const visible = matches.slice(0, limit);
  const visibleBrands = brandMatches.slice(0, limit);

  return (
    <div className="flex flex-col gap-6">
      <div role="group" aria-label="Icon catalog" className="grid grid-cols-1 gap-5 sm:grid-cols-2 lg:grid-cols-3">
        <CatalogCard
          open={set === "icons"}
          title="Icon catalog"
          description="Line icons on a 24px grid. Pick a size and stroke, animate them, and copy the JSX."
          count={`${iconNames.length.toLocaleString("en-US")} icons`}
          tone="bg-lime"
          onOpen={() => {
            openCatalog("icons");
            setLimit(PAGE);
          }}
        >
          {SAMPLE_ICONS.map((Icon, i) => (
            <SampleTile key={i}>
              <Icon className="size-5" strokeWidth={1.75} />
            </SampleTile>
          ))}
        </CatalogCard>
        <CatalogCard
          open={set === "brands"}
          title="Brand catalog"
          description="Logos for the tools, platforms, and companies people know. Copy them as JSX or SVG."
          count={`${brands ? brands.length.toLocaleString("en-US") : "3,400+"} logos`}
          tone="bg-pink"
          onOpen={() => {
            openCatalog("brands");
            setLimit(PAGE);
          }}
        >
          {SAMPLE_BRANDS.map((slug) => (
            <SampleTile key={slug}>
              <BrandGlyph slug={slug} size={20} />
            </SampleTile>
          ))}
        </CatalogCard>
        {/* A catalog of its own kind, still to come. */}
        <CatalogCard
          open={set === "emojis"}
          title="Emoji catalog"
          description="Comic emojis in black and white or color, still or animated. Copy one as a standalone SVG."
          count={`${emojis.length} faces`}
          tone="bg-orange"
          onOpen={() => openCatalog("emojis")}
        >
          <SampleTile>
            <Smile size={24} />
          </SampleTile>
          {["?", "?", "?"].map((q, i) => (
            <SampleTile key={i}>
              <span className="font-display text-base text-ink-muted">{q}</span>
            </SampleTile>
          ))}
        </CatalogCard>
      </div>

      {set === "emojis" ? (
        <EmojiCatalog onCopied={setCopied} copied={copied} />
      ) : (
        <>

      <div className="flex flex-col gap-4 border-2 border-ink bg-paper-raised p-4 shadow-brutal sm:p-5">
        <label htmlFor="icon-search" className="sr-only">
          Search icons
        </label>
        <Input
          id="icon-search"
          type="search"
          icon={<Search />}
          value={query}
          onChange={(e) => {
            setQuery(e.target.value);
            setLimit(PAGE);
          }}
          placeholder={brandsMode ? `Search ${total ? total.toLocaleString("en-US") + " " : ""}brand icons…` : `Search ${total.toLocaleString("en-US")} icons…`}
        />
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="flex flex-wrap gap-5">
            <Segmented label="Size" options={SIZES} value={size} onChange={setSize} />
            {brandsMode ? (
              <Segmented label="Copy as" options={COPY_AS} value={copyAs} onChange={setCopyAs} />
            ) : (
              <Segmented label="Stroke" options={STROKES} value={stroke} onChange={setStroke} />
            )}
          </div>
          <p aria-live="polite" className="font-mono text-xs text-ink-muted">
            {copied ? (
              <span className="bg-lime px-1.5 py-0.5 font-bold text-on-bright">copied {copied}</span>
            ) : (
              `${count.toLocaleString("en-US")} ${brandsMode ? "brand icons" : "icons"}`
            )}
          </p>
        </div>
        {!brandsMode && (
          <div className="flex flex-wrap items-center gap-5 border-t-2 border-dashed border-ink-faint pt-4">
            <Segmented label="Animate" options={ANIMATIONS} value={animation} onChange={setAnimation} />
            {animation !== "none" && (
              <Segmented label="Play on" options={TRIGGERS} value={trigger} onChange={setTrigger} />
            )}
          </div>
        )}
      </div>

      {brandsMode && !brands ? (
        <div className="flex flex-col items-center gap-3 border-2 border-ink bg-paper-raised px-5 py-16 text-center">
          <p className="font-bold">{brandError ? "Couldn't load the brand icons." : "Loading brand icons…"}</p>
        </div>
      ) : brandsMode && visibleBrands.length > 0 ? (
        <ul className="grid grid-cols-3 border-t-2 border-l-2 border-ink sm:grid-cols-4 lg:grid-cols-6">
          {visibleBrands.map((b) => (
            <li key={b.slug} className="border-r-2 border-b-2 border-ink">
              <button
                type="button"
                onClick={() => copyBrand(b)}
                title={b.name}
                aria-label={`Copy ${b.name}${copyAs === "svg" ? " as SVG" : ""}`}
                className="group flex aspect-square w-full cursor-pointer flex-col items-center justify-center gap-2 bg-paper p-2 transition-colors duration-150 hover:bg-lime hover:text-on-bright focus-visible:relative focus-visible:z-10"
              >
                <BrandGlyph slug={b.slug} size={size} />
                <span className="w-full truncate text-center font-mono text-[0.6875rem] text-ink-muted group-hover:text-on-bright">
                  {b.slug}
                </span>
              </button>
            </li>
          ))}
        </ul>
      ) : !brandsMode && visible.length > 0 ? (
        <ul className="grid grid-cols-3 border-t-2 border-l-2 border-ink sm:grid-cols-4 lg:grid-cols-6">
          {visible.map((name) => (
            <li key={name} className="border-r-2 border-b-2 border-ink">
              <button
                type="button"
                onClick={() => copy(name)}
                title={toComponentName(name)}
                aria-label={`Copy ${toComponentName(name)}`}
                className="group flex aspect-square w-full cursor-pointer flex-col items-center justify-center gap-2 bg-paper p-2 transition-colors duration-150 hover:bg-lime hover:text-on-bright focus-visible:relative focus-visible:z-10"
              >
                {animation === "none" ? (
                  <DynamicIcon
                    name={name}
                    size={size}
                    strokeWidth={stroke}
                    aria-hidden
                    fallback={() => <span aria-hidden className="block size-5 bg-ink-faint" />}
                  />
                ) : (
                  <AnimatedIcon key={`${animation}-${trigger}`} animation={animation} trigger={trigger}>
                    <DynamicIcon
                      name={name}
                      size={size}
                      strokeWidth={stroke}
                      aria-hidden
                      fallback={() => <span aria-hidden className="block size-5 bg-ink-faint" />}
                    />
                  </AnimatedIcon>
                )}
                <span className="w-full truncate text-center font-mono text-[0.6875rem] text-ink-muted group-hover:text-on-bright">
                  {name}
                </span>
              </button>
            </li>
          ))}
        </ul>
      ) : (
        <div className="flex flex-col items-center gap-3 border-2 border-ink bg-paper-raised px-5 py-16 text-center">
          <Ghost aria-hidden className="size-10 text-ink-muted" />
          <p className="font-bold">No icons match “{query}”.</p>
          <button
            type="button"
            onClick={() => setQuery("")}
            className="cursor-pointer font-mono text-sm underline decoration-2 underline-offset-4"
          >
            clear search
          </button>
        </div>
      )}

      {count > limit && (
        <Button variant="secondary" className="self-center" onClick={() => setLimit((l) => l + PAGE)}>
          Show more ({(count - limit).toLocaleString("en-US")} left)
        </Button>
      )}
        </>
      )}
    </div>
  );
}
