/**
 * The live map: every example, section design, and lab the docs render, as a
 * lazily loaded client component keyed by its source file.
 *
 * The registries hold only data (names, props, file paths). Importing a
 * component there would put its client code in the bundle of every page that
 * reads the registry, including the docs sidebar on every docs page. Pages
 * render `<Live file={...} />` instead, which loads just the files it shows.
 *
 *   bun scripts/build-live-map.ts   writes src/registry/live.generated.tsx
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { components } from "@/registry/components";
import { sections } from "@/registry/sections";
import { labs } from "@/registry/labs";

export const ROOT = path.join(import.meta.dir, "..");
export const OUT = "src/registry/live.generated.tsx";

/** Every file the docs render live, in registry order. */
export function liveFiles(): string[] {
  const files = [
    ...components.flatMap((c) => c.examples.map((e) => e.file)),
    ...sections.flatMap((s) => s.variants.map((v) => v.file)),
    ...labs.map((l) => l.file),
  ];
  return [...new Set(files)];
}

/** "default" for a default export, else the export named after the file (ShapeRollerLab.tsx → ShapeRollerLab). */
export function exportName(file: string): string {
  const source = readFileSync(path.join(ROOT, file), "utf8");
  if (/^export default /m.test(source)) return "default";
  const name = path.basename(file, path.extname(file));
  if (new RegExp(`^export (async )?(function|const) ${name}\\b`, "m").test(source)) return name;
  throw new Error(`${file}: no default export and no export named ${name}`);
}

const importPath = (file: string) => file.replace(/^src\//, "@/").replace(/\.tsx?$/, "");

export function renderLiveMap(): string {
  const rows = liveFiles().map((file) => {
    const name = exportName(file);
    const load = name === "default" ? `import("${importPath(file)}")` : `import("${importPath(file)}").then((m) => m.${name})`;
    return `  "${file}": dynamic(() => ${load}),`;
  });
  return `"use client";

// Generated by scripts/build-live-map.ts from the registries. Do not edit.
// Each entry loads its file only when it renders, so a page ships just the
// examples, sections, and labs it shows.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const live: Record<string, ComponentType<any>> = {
${rows.join("\n")}
};
`;
}
