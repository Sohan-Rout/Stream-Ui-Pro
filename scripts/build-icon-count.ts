/**
 * Writes how many Lucide icons the icon browser offers, for the mobile menu's
 * counts. Lucide exposes its icon names from a client module, which a server
 * component can't read and which would ship the whole list to every page if
 * the header imported it, so the number is generated here instead.
 *
 *   bun scripts/build-icon-count.ts   writes src/lib/icon-count.generated.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { iconNames } from "lucide-react/dynamic";

/** The same list the icon browser shows, so the two counts always agree. */
export const iconCount = () => iconNames.length;

export const renderIconCount = () => `// Generated by scripts/build-icon-count.ts. Do not edit.
export const LUCIDE_ICON_COUNT = ${iconCount()};
`;

if (import.meta.main) {
  writeFileSync(path.join(import.meta.dir, "..", "src/lib/icon-count.generated.ts"), renderIconCount());
  console.log(`icon count: ${iconCount()} → src/lib/icon-count.generated.ts`);
}
